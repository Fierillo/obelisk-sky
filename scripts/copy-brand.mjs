// Copy the real Obelisk icons from the vendored obelisk-dex snapshot into the
// client, so sky never ships a redrawn logo. Run after vendor-obelisk.sh.
import { cpSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const SRC = 'vendor/obelisk/public';
const OUT = 'client/public';
for (const f of ['favicon.ico', 'icon-192.png', 'icon-512.png', 'obelisk-favicon.png', 'obelisk.stl']) {
  cpSync(`${SRC}/${f}`, `${OUT}/${f}`);
}
rmSync(`${OUT}/favicon.svg`, { force: true });
// Mirrors obelisk-dex src/app/manifest.ts, renamed for the village.
writeFileSync(`${OUT}/manifest.webmanifest`, JSON.stringify({
  name: 'Obelisk Sky',
  short_name: 'Sky',
  description: 'The Obelisk village: walk to a channel and talk there.',
  start_url: '/',
  display: 'standalone',
  background_color: '#0a0a0a',
  theme_color: '#0a0a0a',
  icons: [
    { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
    { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));
// The app's own stylesheet (Tailwind v4 + La Crypta tokens + the SDK login
// re-skin), compiled by sky's Vite for the re-hosted login modal and chat
// message renderer. Only the
// files that render inside sky are scanned for utilities.
const globals = readFileSync('vendor/obelisk/src/app/globals.css', 'utf8').replace(
  '@import "tailwindcss";',
  [
    '@import "tailwindcss" source(none);',
    '@source "../../vendor/obelisk/src/app/*/app/login";',
    '@source "../../vendor/obelisk/src/components/ui";',
    '@source "../../vendor/obelisk/src/utils/style";',
    '@source "../../vendor/obelisk/src/assets/icons";',
    // The chat's message renderer (client/src/chat/SkyMessageContent.tsx).
    '@source "../../vendor/obelisk/src/components/chat/message";',
    '@source "../../vendor/obelisk/src/components/chat/gallery";',
    '@source "../../vendor/obelisk/src/components/common";',
    '@source "../../vendor/obelisk/src/assets/brand";',
  ].join('\n'),
);
// Paths in globals.css are relative to src/app; the copy lives in client/src.
const rebased = globals.replace(/url\((['"]?)\.\.\/assets\//g, 'url($1../../vendor/obelisk/src/assets/');
writeFileSync('client/src/obelisk.generated.css', `/* Generated by scripts/copy-brand.mjs from obelisk-dex src/app/globals.css. Do not edit. */\n${rebased}`);
console.log('brand assets and app stylesheet copied');

// Copy what sky still takes from the vendored obelisk-dex snapshot (the
// obelisk model and the app stylesheet) and write the manifest. Sky's own
// icons (the cloud with the Obelisk) come from scripts/make-icons.mjs.
// Run after vendor-obelisk.sh.
import { cpSync, readFileSync, writeFileSync } from 'node:fs';

const SRC = 'vendor/obelisk/public';
const OUT = 'client/public';
cpSync(`${SRC}/obelisk.stl`, `${OUT}/obelisk.stl`);
// Shaped like obelisk-dex src/app/manifest.ts; the app lives at /app.
writeFileSync(`${OUT}/manifest.webmanifest`, JSON.stringify({
  name: 'Obelisk Sky',
  short_name: 'Sky',
  description: 'The Obelisk village: walk to a channel and talk there.',
  start_url: '/app',
  display: 'standalone',
  // The village is played sideways on phones (ui/orientation.ts asks the browser too).
  orientation: 'landscape',
  background_color: '#cfeaff',
  theme_color: '#cfeaff',
  icons: [
    { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    { src: '/brand/sky-mark-flat.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
  ],
}, null, 2));
// The app's own stylesheet (Tailwind v4 + La Crypta tokens + the SDK login
// re-skin), compiled by sky's Vite for the re-hosted login modal and chat
// message renderer. Only the
// files that render inside sky are scanned for utilities.
const globals = readFileSync('vendor/obelisk/src/app/globals.css', 'utf8').replace(
  '@import "tailwindcss";',
  [
    '@import "tailwindcss" source(none);',
    '@source "../../vendor/obelisk/src/app/*/app/login";',
    '@source "../../vendor/obelisk/src/components/ui";',
    '@source "../../vendor/obelisk/src/utils/style";',
    '@source "../../vendor/obelisk/src/assets/icons";',
    // The chat's message renderer (client/src/chat/SkyMessageContent.tsx).
    '@source "../../vendor/obelisk/src/components/chat/message";',
    '@source "../../vendor/obelisk/src/components/chat/gallery";',
    '@source "../../vendor/obelisk/src/components/common";',
    '@source "../../vendor/obelisk/src/assets/brand";',
    // The message bar (client/src/chat/composer): the app's composer pieces,
    // pickers, reply bar and attachments, and sky's own skin over them.
    '@source "../../vendor/obelisk/src/components/chat/composer";',
    '@source "../../vendor/obelisk/src/components/chat/picker";',
    '@source "../../vendor/obelisk/src/components/chat/mentions";',
    '@source "../../vendor/obelisk/src/components/chat/slash";',
    '@source "../../vendor/obelisk/src/components/identity";',
    '@source "../../vendor/obelisk/src/components/media/library/MediaThumb.tsx";',
    '@source "../../vendor/obelisk/src/app/*/app/panes/channel/ComposerReplyBar.tsx";',
    '@source "../../vendor/obelisk/src/app/*/app/panes/channel/ComposerAttachments.tsx";',
    '@source "../../vendor/obelisk/src/utils/chat/picker";',
    '@source "./chat/composer";',
    // The profile editor (client/src/profile): the app's desktop form and its appearance editor.
    '@source "../../vendor/obelisk/src/app/*/app/settings/EditProfileForm.tsx";',
    '@source "../../vendor/obelisk/src/app/*/app/settings/ProfileFormField.tsx";',
    '@source "../../vendor/obelisk/src/components/settings/account";',
    '@source "./profile";',
  ].join('\n'),
);
// Paths in globals.css are relative to src/app; the copy lives in client/src.
const rebased = globals.replace(/url\((['"]?)\.\.\/assets\//g, 'url($1../../vendor/obelisk/src/assets/');
writeFileSync('client/src/obelisk.generated.css', `/* Generated by scripts/copy-brand.mjs from obelisk-dex src/app/globals.css. Do not edit. */\n${rebased}`);
console.log('obelisk model, manifest and app stylesheet written');
